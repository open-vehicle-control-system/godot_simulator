"""Build the packs the simulator bundles: the default track and the default vehicle.

    python3 tools/default_packs.py [OUT_DIR]

OUT_DIR is simulator/default_packs by default, where the built packs are committed; the
sources of their textures go to build/default_packs_work. The track is generated from code
(default_track.py), from fixed seeds, and is CC0. The vehicle's model is built from
"Generic Sedan Car" (CC BY 4.0, credited in its pack), whose source is not in the repository:
download it to build/sedan_src/small.glb (default_car_model.py says how); without it the
vehicle pack is left as it is. The track's trees are rendered from Poly Haven's models by
tree_impostors.py, once, which needs BLENDER_PYTHON (a Python with Blender's bpy) the first time;
its sky is downloaded once. The textures are compressed into DDS by Godot's own encoders
(compress_textures.gd, run with the Godot named by the GODOT environment variable).

Needs numpy and Pillow, and Godot 4.6 to compress the textures.
"""

import json
import shutil
import sys
from pathlib import Path

import default_car_model
import default_track
import default_vehicle
import pack_experiment
import tree_impostors

REPOSITORY = Path(__file__).resolve().parent.parent
OUT = REPOSITORY / "simulator" / "default_packs"
WORK = REPOSITORY / "build" / "default_packs_work"
LICENCE = (
    "This pack was generated by tools/default_packs.py and is dedicated to the public domain\n"
    "under CC0 1.0: https://creativecommons.org/publicdomain/zero/1.0/\n"
    "Its trees are impostors rendered from Poly Haven's fir_tree_01, pine_tree_01 and\n"
    "jacaranda_tree (Rico Cilliers and Rob Tuytel) and its sky, sky.hdr, is Poly Haven's\n"
    "kloofendal_48d_partly_cloudy_puresky at 2K (Greg Zaal and Jarod Guest), all CC0:\n"
    "https://polyhaven.com\n"
)


def write_manifest(directory, manifest, licence):
    """Write a pack's pack.json and its licence."""
    (directory / "pack.json").write_text(json.dumps(manifest, indent=2) + "\n")
    (directory / "LICENCE.txt").write_text(licence)


def emptied(directory):
    """Return `directory`, removed first if it was there."""
    if directory.exists():
        shutil.rmtree(directory)
    return directory


def build(out, work, car_source=default_car_model.SOURCE):
    """Write the packs into `out`, each emptied first; return the DDS compression jobs left.

    The vehicle pack is written only when `car_source` exists.
    """
    if car_source.exists():
        vehicle = emptied(out / default_vehicle.VEHICLE_ID)
        write_manifest(vehicle, default_vehicle.write(vehicle, car_source), default_vehicle.LICENCE)
    track = emptied(out / default_track.TRACK_ID)
    manifest, jobs = default_track.write(track, work / default_track.TRACK_ID)
    write_manifest(track, manifest, LICENCE)
    for _, _, compressed in jobs:
        compressed.parent.mkdir(parents=True, exist_ok=True)
    return jobs


def main(out):
    """Build both packs into `out`, textures compressed."""
    tree_impostors.ensure()
    pack_experiment.compress_textures(build(out, WORK))
    print(f"{out}: {default_track.TRACK_ID}")
    if default_car_model.SOURCE.exists():
        print(f"{out}: {default_vehicle.VEHICLE_ID}")
    else:
        print(f"{default_car_model.SOURCE} is missing: {default_vehicle.VEHICLE_ID} left as it was")


if __name__ == "__main__":
    if len(sys.argv) > 2:
        sys.exit(__doc__)
    main(Path(sys.argv[1]).resolve() if len(sys.argv) == 2 else OUT)
